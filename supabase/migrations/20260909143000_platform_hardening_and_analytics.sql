create or replace view public.v_standings with (security_invoker=true) as
with played as (
 select p.temporada_id,p.id partido_id,p.local_equipo_id equipo_id,p.goles_local gf,p.goles_visitante ga,
  (p.goles_local>p.goles_visitante)::int pg,(p.goles_local=p.goles_visitante)::int pe,(p.goles_local<p.goles_visitante)::int pp
 from public.partidos p where p.goles_local is not null and p.goles_visitante is not null
 union all
 select p.temporada_id,p.id,p.visitante_equipo_id,p.goles_visitante,p.goles_local,
  (p.goles_visitante>p.goles_local)::int,(p.goles_visitante=p.goles_local)::int,(p.goles_visitante<p.goles_local)::int
 from public.partidos p where p.goles_local is not null and p.goles_visitante is not null
), agg as (
 select temporada_id,equipo_id,count(*) pj,sum(pg) pg,sum(pe) pe,sum(pp) pp,sum(gf) gf,sum(ga) ga from played group by temporada_id,equipo_id
)
select e.temporada_id,e.id equipo_id,e.club_id,c.nombre club,e.rama,e.categoria,e.division,e.equipo_codigo,
 coalesce(a.pj,0)::bigint pj,coalesce(a.pg,0)::bigint pg,coalesce(a.pe,0)::bigint pe,coalesce(a.pp,0)::bigint pp,
 coalesce(a.gf,0)::bigint gf,coalesce(a.ga,0)::bigint ga,(coalesce(a.gf,0)-coalesce(a.ga,0))::bigint dif,
 (coalesce(a.pg,0)*2+coalesce(a.pe,0))::bigint puntos
from public.equipos e join public.clubes c on c.id=e.club_id
left join agg a on a.temporada_id=e.temporada_id and a.equipo_id=e.id where e.activo;
grant select on public.v_standings to anon,authenticated;

create or replace view public.v_player_totals with (security_invoker=true) as
select j.id jugador_id,j.nombre,j.apellido,pl.equipo_id,e.club_id,c.nombre club,e.rama,e.categoria,e.division,
 count(distinct pa.partido_id) partidos,coalesce(sum(pa.goles),0) goles,
 round(coalesce(sum(pa.goles),0)::numeric/nullif(count(distinct pa.partido_id),0),2) goles_por_partido,
 coalesce(sum(pa.exclusiones_2min),0) exclusiones_2min,coalesce(sum(pa.tarjeta_amarilla),0) amarillas,coalesce(sum(pa.tarjeta_roja),0) rojas
from public.jugadores j left join public.planteles pl on pl.jugador_id=j.id
left join public.equipos e on e.id=pl.equipo_id left join public.clubes c on c.id=e.club_id
left join public.participaciones pa on pa.jugador_id=j.id and (pl.equipo_id is null or pa.equipo_id=pl.equipo_id)
group by j.id,j.nombre,j.apellido,pl.equipo_id,e.club_id,c.nombre,e.rama,e.categoria,e.division;
grant select on public.v_player_totals to anon,authenticated;


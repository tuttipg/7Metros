create or replace view public.v_global_summary with (security_invoker=true) as
select
 (select count(*) from public.clubes where activo) clubes,
 (select count(*) from public.equipos where activo) equipos,
 (select count(*) from public.jugadores where activo) jugadores,
 (select count(*) from public.partidos) partidos,
 (select count(*) from public.partidos where goles_local is not null and goles_visitante is not null) partidos_con_resultado,
 (select coalesce(sum(goles_local+goles_visitante),0) from public.partidos where goles_local is not null and goles_visitante is not null) goles,
 (select round(avg((goles_local+goles_visitante)::numeric),1) from public.partidos where goles_local is not null and goles_visitante is not null) promedio_goles,
 (select count(*) from public.partidos where planilla_url is not null) partidos_con_planilla,
 (select count(*) from public.videos_partidos) videos,
 (select count(*) from public.videos_partidos where procesado_ia) videos_procesados_ia;
grant select on public.v_global_summary to anon,authenticated;

create or replace view public.v_competition_catalog with (security_invoker=true) as
select e.temporada_id,t.nombre temporada,e.rama,e.categoria,e.division,
 count(*) filter(where e.activo) equipos,
 count(distinct p.id) partidos,
 count(distinct p.id) filter(where p.goles_local is not null and p.goles_visitante is not null) partidos_con_resultado,
 min(p.fecha) fecha_desde,max(p.fecha) fecha_hasta
from public.equipos e join public.temporadas t on t.id=e.temporada_id
left join public.partidos p on p.temporada_id=e.temporada_id and (p.local_equipo_id=e.id or p.visitante_equipo_id=e.id)
group by e.temporada_id,t.nombre,e.rama,e.categoria,e.division;
grant select on public.v_competition_catalog to anon,authenticated;


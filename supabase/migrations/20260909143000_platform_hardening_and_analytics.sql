create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated;

create or replace function private.es_admin()
returns boolean language sql stable security definer
set search_path = pg_catalog, public
as $$ select exists (select 1 from public.perfiles where id=auth.uid() and rol='admin' and activo=true); $$;

create or replace function private.es_colaborador()
returns boolean language sql stable security definer
set search_path = pg_catalog, public
as $$ select exists (select 1 from public.perfiles where id=auth.uid() and rol in ('admin','colaborador','analista') and activo=true); $$;

revoke all on function private.es_admin() from public;
revoke all on function private.es_colaborador() from public;
grant execute on function private.es_admin() to authenticated;
grant execute on function private.es_colaborador() to authenticated;

create or replace function public.es_admin()
returns boolean language sql stable security invoker
set search_path = pg_catalog, public, private
as $$ select private.es_admin(); $$;

create or replace function public.es_colaborador()
returns boolean language sql stable security invoker
set search_path = pg_catalog, public, private
as $$ select private.es_colaborador(); $$;

revoke all on function public.es_admin() from public;
revoke all on function public.es_colaborador() from public;
grant execute on function public.es_admin() to authenticated;
grant execute on function public.es_colaborador() to authenticated;

